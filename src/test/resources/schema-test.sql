/* =========================================================
   LIBRIFLOW - BASE DE DATOS PARA PRUEBAS CON DOCKER
   ========================================================= */


/* =========================================================
   1. USUARIO
   ========================================================= */

CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(100) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(100) NOT NULL,
    CORREO_ELECTRONICO VARCHAR2(150) NOT NULL,
    TELEFONO VARCHAR2(20) NOT NULL,
    ESTADO_CUENTA VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    FECHA_DESBLOQUEO DATE,
    FECHA_CREACION DATE DEFAULT SYSDATE,

    CONSTRAINT PK_USUARIO
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UK_USUARIO_CORREO
        UNIQUE (CORREO_ELECTRONICO)
);


/* =========================================================
   2. CREDENCIAL
   ========================================================= */

CREATE TABLE CREDENCIAL (
    ID_CREDENCIAL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    CONTRASENA VARCHAR2(255) NOT NULL,

    CONSTRAINT PK_CREDENCIAL
        PRIMARY KEY (ID_CREDENCIAL),

    CONSTRAINT UK_CREDENCIAL_USUARIO
        UNIQUE (ID_USUARIO),

    CONSTRAINT FK_CREDENCIAL_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO(ID_USUARIO)
);


/* =========================================================
   3. ROL
   ========================================================= */

CREATE TABLE ROL (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ROL VARCHAR2(20) DEFAULT 'USUARIO' NOT NULL,

    CONSTRAINT PK_ROL
        PRIMARY KEY (ID_ROL),

    CONSTRAINT UK_ROL_USUARIO
        UNIQUE (ID_USUARIO),

    CONSTRAINT FK_ROL_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO(ID_USUARIO)
);


/* =========================================================
   4. LIBRO
   ========================================================= */

CREATE TABLE LIBRO (
    ID_LIBRO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO VARCHAR2(200) NOT NULL,
    AUTOR VARCHAR2(150) NOT NULL,
    EDITORIAL VARCHAR2(150),
    GENERO VARCHAR2(100),

    CONSTRAINT PK_LIBRO
        PRIMARY KEY (ID_LIBRO)
);


/* =========================================================
   5. PUBLICACION_LF
   ========================================================= */

CREATE TABLE PUBLICACION_LF (
    ID_PUBLICACION_LF NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LIBRO NUMBER NOT NULL,
    FECHA_PUBLICACION DATE DEFAULT SYSDATE,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO',
    CANTIDAD NUMBER NOT NULL,
    SINOPSIS VARCHAR2(3000),
    ES_VENTA NUMBER(1,0) DEFAULT 0 NOT NULL,
    ES_RENTA NUMBER(1,0) DEFAULT 0 NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_PUBLICACION_LF
        PRIMARY KEY (ID_PUBLICACION_LF),

    CONSTRAINT FK_PUBLICACION_LF_LIBRO
        FOREIGN KEY (ID_LIBRO)
        REFERENCES LIBRO(ID_LIBRO)
);


/* =========================================================
   6. PUBLICACION_US
   ========================================================= */

CREATE TABLE PUBLICACION_US (
    ID_PUBLICACION_US NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_LIBRO NUMBER NOT NULL,
    FECHA DATE DEFAULT SYSDATE,
    SINOPSIS VARCHAR2(3000) NOT NULL,
    ESTADO VARCHAR2(50) DEFAULT 'ACTIVO' NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_PUBLICACION_US
        PRIMARY KEY (ID_PUBLICACION_US),

    CONSTRAINT FK_PUBLICACION_US_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO(ID_USUARIO),

    CONSTRAINT FK_PUBLICACION_US_LIBRO
        FOREIGN KEY (ID_LIBRO)
        REFERENCES LIBRO(ID_LIBRO)
);


/* =========================================================
   7. IMAGEN
   ========================================================= */

CREATE TABLE IMAGEN (
    ID_IMAGEN NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PUBLICACION_US NUMBER,
    ID_PUBLICACION_LF NUMBER,
    IMAGEN VARCHAR2(200) NOT NULL,
    TIPO NUMBER(1,0) NOT NULL,

    CONSTRAINT PK_IMAGEN
        PRIMARY KEY (ID_IMAGEN),

    CONSTRAINT FK_IMAGEN_PUBLICACION_US
        FOREIGN KEY (ID_PUBLICACION_US)
        REFERENCES PUBLICACION_US(ID_PUBLICACION_US),

    CONSTRAINT FK_IMAGEN_PUBLICACION_LF
        FOREIGN KEY (ID_PUBLICACION_LF)
        REFERENCES PUBLICACION_LF(ID_PUBLICACION_LF)
);


/* =========================================================
   8. TRANSACCION
   ========================================================= */

CREATE TABLE TRANSACCION (
    ID_TRANSACCION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_COMPRADOR NUMBER NOT NULL,
    FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    SUBTOTAL NUMBER(10,2) NOT NULL,
    COSTO_ENVIO NUMBER(10,2) DEFAULT 0 NOT NULL,
    TOTAL NUMBER(10,2) NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_TRANSACCION
        PRIMARY KEY (ID_TRANSACCION),

    CONSTRAINT FK_TRANSACCION_COMPRADOR
        FOREIGN KEY (ID_COMPRADOR)
        REFERENCES USUARIO(ID_USUARIO)
);


/* =========================================================
   9. DETALLE_TRANSACCION
   ========================================================= */

CREATE TABLE DETALLE_TRANSACCION (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_TRANSACCION NUMBER NOT NULL,
    ID_PUBLICACION_US NUMBER,
    ID_PUBLICACION_LF NUMBER,
    ID_VENDEDOR NUMBER,
    TIPO_OPERACION VARCHAR2(10) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    GANANCIA_LIBRIFLOW NUMBER(10,2) NOT NULL,
    GANANCIA_VENDEDOR NUMBER(10,2),

    CONSTRAINT PK_DETALLE_TRANSACCION
        PRIMARY KEY (ID_DETALLE),

    CONSTRAINT FK_DT_TRANSACCION
        FOREIGN KEY (ID_TRANSACCION)
        REFERENCES TRANSACCION(ID_TRANSACCION),

    CONSTRAINT FK_DT_PUBLICACION_US
        FOREIGN KEY (ID_PUBLICACION_US)
        REFERENCES PUBLICACION_US(ID_PUBLICACION_US),

    CONSTRAINT FK_DT_PUBLICACION_LF
        FOREIGN KEY (ID_PUBLICACION_LF)
        REFERENCES PUBLICACION_LF(ID_PUBLICACION_LF),

    CONSTRAINT FK_DT_VENDEDOR
        FOREIGN KEY (ID_VENDEDOR)
        REFERENCES USUARIO(ID_USUARIO)
);


/* =========================================================
   10. DETALLE_RENTA
   ========================================================= */

CREATE TABLE DETALLE_RENTA (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_DETALLE_TRANSACCION NUMBER NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_LIMITE DATE NOT NULL,
    FECHA_DEVOLUCION DATE,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    PENALIZACION NUMBER(1,0) DEFAULT 0 NOT NULL,
    CODIGO VARCHAR2(10),

    CONSTRAINT PK_DETALLE_RENTA
        PRIMARY KEY (ID_DETALLE),

    CONSTRAINT FK_RENTA_DETALLE_TRANSACCION
        FOREIGN KEY (ID_DETALLE_TRANSACCION)
        REFERENCES DETALLE_TRANSACCION(ID_DETALLE)
);


/* =========================================================
   11. RESENA
   ========================================================= */

CREATE TABLE RESENA (
    ID_RESENA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_PUBLICACION_LF NUMBER NOT NULL,
    COMENTARIO VARCHAR2(1000) NOT NULL,
    CALIFICACION NUMBER(1,0) NOT NULL,
    FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_RESENA
        PRIMARY KEY (ID_RESENA),

    CONSTRAINT FK_RESENA_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO(ID_USUARIO),

    CONSTRAINT FK_RESENA_PUBLICACION
        FOREIGN KEY (ID_PUBLICACION_LF)
        REFERENCES PUBLICACION_LF(ID_PUBLICACION_LF)
);